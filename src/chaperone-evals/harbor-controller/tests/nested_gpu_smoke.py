#!/usr/bin/env python3
r"""Opt-in AF3 check through the real controller-generated scientific worker.

Run from an existing GPU allocation, using the controller's Python environment::

    python src/chaperone-evals/harbor-controller/tests/nested_gpu_smoke.py \
      --root /shared/new/nested-af3 \
      --agent-image /shared/fresh-containers/chaperone-agent.sif \
      --container-dir /shared/fresh-containers \
      --af3-weights /shared/weights/alphafold3

The host interpreter needs the real controller dependencies, including Harbor
(install the eval project with ``uv pip install -e src/chaperone-evals`` in a
controller environment). The fresh agent image uses
``/opt/chaperone/.venv/bin/python``. No LLM, API call, controller task, or new
Slurm submission is made. The ordinary ExecutionEngine runs one 48-residue AF3
prediction locally, with its normal inference schedule and one sample.

The helper uses the real snapshot audit, workspace staging, runtime identity and
Slurm-Python preparation functions. Only its explicit workspace, scientific
image directory, weights and standard controller runtime paths are mounted.
Source wrappers come from the sanitized workspace, not host site-packages.
--prepare-only stages the same check without requiring a GPU allocation or
running Apptainer; it prints the exact executable command for later use.
Choose an empty --root for every image validation. All outputs remain there.
"""

import argparse
import os
from pathlib import Path
import shlex
import shutil
import subprocess
import sys
import json


CONTROLLER = Path(__file__).resolve().parents[1]
REPO = CONTROLLER.parents[2]
WORKER_PYTHON = "/opt/chaperone/.venv/bin/python"


DRIVER = '''"""One nested scientific prediction; generated by nested_gpu_smoke.py."""
import os
from pathlib import Path
import numpy as np

workspace = Path(__file__).resolve().parent
# Exercise the same restricted nested-bind behavior as the harness agent.
os.environ["HARBOR_HOST_WORKSPACE"] = str(workspace)
import chaperone
from chaperone import ExecutionEngine, PipelineDataHandler, init_cli
from chaperone.execution_tracking import load_execution_records
from blocks import Blocks
from biotite.structure import filter_amino_acids, get_residue_starts
from biotite.structure.io.pdb import PDBFile

assert Path(chaperone.__file__).resolve().is_relative_to(workspace / "chaperone/src")
init_cli(blocks=[Blocks["af3"]])
reference = next(PipelineDataHandler.from_paths(
    [str(workspace / "inputs/reference.pdb")], name="reference"
).get_data(load=True))
protein = reference.atom_array[filter_amino_acids(reference.atom_array)]
chain = protein[protein.chain_id == protein.chain_id[0]]
starts = get_residue_starts(chain, add_exclusive_stop=True)
assert len(starts) - 1 >= 48
atoms = chain[:starts[48]].copy()
atoms.chain_id[:] = "A"
input_path = workspace / "reference48.pdb"
pdb = PDBFile()
pdb.set_structure(atoms)
pdb.write(str(input_path))
handler = PipelineDataHandler.from_paths([str(input_path)], name="reference48")
expected = next(handler.get_data(load=True)).sequence
cache = workspace / ".cache/af3_jax"
assert Path(os.environ["AF3_JAX_CACHE_DIR"]).resolve() == cache
probe = cache / ".write-probe"
probe.write_text("writable")
probe.unlink()
block = Blocks["af3"](diffusion_batch_size=1)
assert Path(block.jax_cache_dir).resolve() == cache
engine = ExecutionEngine(rundir=workspace / "af3-run")
result = engine.run(block, data=handler, run_args={"mode": "local", "max_workers": 1, "max_retries": 0},
                    job_args={"num_chunks": 1})
assert len(result) == 1
output = next(result.get_data(which="last", load=True))
assert output.name == "af3" and output.sequence == expected
assert output.atom_array is not None and np.isfinite(output.atom_array.coord).all()
assert float(np.ptp(output.atom_array.coord, axis=0).max()) < 1000
assert len(set(zip(output.atom_array.chain_id, output.atom_array.res_id))) == 48
for key in ("plddt", "ptm"):
    assert np.isfinite(float(output.metrics["af3"][key]))
records = load_execution_records(engine.rundir / "af3")
assert len(records) == 1 and records[0].status == "succeeded"
assert records[0].allocated_gpus == 1 and records[0].gpu_seconds > 0
assert records[0].job_id == os.environ["SLURM_JOB_ID"], "Local check must use the existing allocation"
print("NESTED CONTROLLER GPU PASS", output.path, output.metrics["af3"], flush=True)
'''


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--root", required=True, type=Path)
    parser.add_argument("--agent-image", required=True, type=Path)
    parser.add_argument("--container-dir", required=True, type=Path)
    parser.add_argument("--af3-weights", required=True, type=Path)
    parser.add_argument("--repo", type=Path, default=REPO)
    parser.add_argument("--input", type=Path, help="Protein PDB with at least 48 residues in its first protein chain")
    parser.add_argument("--prepare-only", action="store_true")
    args = parser.parse_args(argv)
    repo = args.repo.expanduser().resolve()
    root = args.root.expanduser().resolve()
    image = args.agent_image.expanduser().resolve()
    containers = args.container_dir.expanduser().resolve()
    weights = args.af3_weights.expanduser().resolve()
    source = (args.input or repo / "examples/benchmarks/ppi/files/4zxb_cropped.pdb").expanduser().resolve()
    if not args.prepare_only and not os.environ.get("SLURM_JOB_ID"):
        parser.error("Run inside an existing GPU allocation, or use --prepare-only")
    if not image.is_file() or image.suffix != ".sif":
        parser.error("--agent-image must name a built fresh agent SIF")
    if not containers.is_dir() or not (containers / "alphafold3.sif").is_file():
        parser.error("--container-dir must contain the freshly built alphafold3.sif")
    if not weights.is_dir() or not source.is_file():
        parser.error("AF3 weights directory and input PDB must exist")
    if root.exists() and any(root.iterdir()):
        parser.error("--root must be a new or empty directory")
    sys.path.insert(0, str(repo / "src/chaperone-evals/harbor-controller"))
    try:
        from environments.apptainer import ApptainerEnvironment
        from scripts.snapshot_harness import build
        from site_config import RUNTIME_BINDS, get_site
    except ModuleNotFoundError as error:
        parser.error(f"Install the real controller dependencies (uv pip install -e src/chaperone-evals): {error}")
    root.mkdir(parents=True, exist_ok=True)
    root.chmod(0o700)
    workspace = root / "workspace"
    cache = workspace / ".cache/af3_jax"
    site_path = root / "site.json"
    site_path.write_text(json.dumps({
        "agent_image": str(image), "worker_image": str(image), "worker_python": WORKER_PYTHON,
        "runtime_binds": [*RUNTIME_BINDS, str(containers), str(weights)],
        "environment": {"CHAPERONE_CONTAINER_DIRS": str(containers),
                        "ALPHAFOLD3_WEIGHTS_DIR": str(weights), "AF3_JAX_CACHE_DIR": str(cache)},
    }, indent=2) + "\n")
    os.environ["CHAPERONE_EVAL_SITE"] = "portable"
    os.environ["CHAPERONE_EVAL_SITE_CONFIG"] = str(site_path)
    # Explicit arguments must win over inherited controller image overrides.
    for name in ("CHAPERONE_EVAL_AGENT_IMAGE", "CHAPERONE_EVAL_WORKER_IMAGE", "CHAPERONE_EVAL_BASELINE_IMAGE"):
        os.environ.pop(name, None)
    seed = build(repo, root / "seeds")
    inputs = root / "task-inputs"
    inputs.mkdir()
    shutil.copy2(source, inputs / "reference.pdb")
    ApptainerEnvironment._prepare_workspace(workspace, seed, inputs)
    cache.mkdir(parents=True)
    runtime = root / ".runtime"
    ApptainerEnvironment._prepare_runtime_identity(runtime, workspace)
    wrapper = runtime / "slurm-python"
    ApptainerEnvironment._prepare_slurm_python(
        wrapper, workspace, image, site_environment=get_site()["environment"],
    )
    driver = workspace / "nested_af3.py"
    compile(DRIVER, str(driver), "exec")
    driver.write_text(DRIVER)
    command = [str(wrapper), str(driver), "--test", "--local", f"--rundir={workspace / 'af3-run'}"]
    print("Nested GPU command:", shlex.join(command), flush=True)
    if not args.prepare_only:
        subprocess.run(command, cwd=workspace, check=True)


if __name__ == "__main__":
    main()
