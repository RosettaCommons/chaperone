"""Execute staged compiled-block commands in isolated Modal Sandboxes.

The normal engine still owns chunking, retries, compilation and lineage. Only
the external command runs remotely. Each attempt has its own filesystem; the
absolute chunk path is preserved so JSON inputs and output metadata need no
string rewriting. Authentication is handled exclusively by Modal's SDK.
"""

from __future__ import annotations

from contextvars import ContextVar
from dataclasses import dataclass, field
import hashlib
import logging
from pathlib import Path
import re
import shutil
import subprocess
import tarfile
import tempfile
import threading

from chaperone.execution_tracking import RemoteAllocation

logger = logging.getLogger(__name__)
_COMMAND_CONTEXT = ContextVar("modal_command_context", default=None)
_IMAGE_LOCK = threading.Lock()  # HPCCM's output format is process-global.


def current_command_context():
    return _COMMAND_CONTEXT.get()


def gpu_request(settings, job_args):
    """Preserve GPU counts, while mapping hardware classes through Modal settings."""
    if not job_args or not job_args.wants_gpu:
        return None
    gpu = settings.CHAPERONE_MODAL_GPU_MAP.get(
        job_args.gpu_class, settings.CHAPERONE_MODAL_GPU
    )
    count = 1
    if job_args.gres:
        match = re.fullmatch(r"gpu(?::[^:,\s]+)?:([1-9]\d*)", job_args.gres)
        if not match:
            raise ValueError(f"Unsupported Modal GPU count request: {job_args.gres}")
        count = int(match[1])
    if ":" in gpu:
        raise ValueError(
            "CHAPERONE_MODAL_GPU selects a type; set GPU count through JobArgs.gres"
        )
    return gpu if count == 1 else f"{gpu}:{count}"


def write_image_context(image, directory: Path):
    """Include only explicitly declared COPY sources in a private build context."""
    prepared = image._clone()
    prepared._copies = []
    for index, (src, dst) in enumerate(image._copies):
        source = Path(src).resolve(strict=True)
        name = f"copy-{index}"
        if source.is_dir():
            shutil.copytree(source, directory / name)
        else:
            shutil.copy2(source, directory / name)
        prepared._copies.append((name, dst))
    dockerfile = directory / "Dockerfile"
    with _IMAGE_LOCK:
        dockerfile.write_text(prepared.to_dockerfile())
    return dockerfile


def stage_file(source: str | Path, directory: Path) -> Path:
    """Copy an external input, retaining basename and avoiding name collisions."""
    source = Path(source).resolve(strict=True)
    if source.is_relative_to(directory.parent.resolve()):
        return source
    digest = hashlib.sha256(str(source).encode()).hexdigest()[:16]
    destination = directory / digest / source.name
    destination.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(source, destination)
    return destination.absolute()


@dataclass
class CommandContext:
    image: object = None
    explicit_binds: list = field(default_factory=list)
    allocation: RemoteAllocation = field(
        default_factory=lambda: RemoteAllocation("modal")
    )

    def build_command(self, image, args, env, binds, exec_mode=None):
        if image.is_existing:
            raise ValueError(
                f"Modal needs a buildable image recipe; '{image.name}' is a local SIF."
            )
        if self.image is not None and self.image is not image:
            raise ValueError(
                "One compiled Modal block cannot use multiple container images"
            )
        self.image = image
        self.explicit_binds.extend(binds or [])
        values = {**(image._command_config or {}).get("env", {}), **(env or {})}
        values = {k: v() if callable(v) else v for k, v in values.items()}
        mode = exec_mode or (image._command_config or {}).get("exec_mode", "run")
        if mode == "run" and image._runscript and image._runscript.strip() != '"$@"':
            args = ["/bin/sh", "-c", image._runscript, image.name, *args]
        return ["env", *(f"{k}={v}" for k, v in values.items()), *args]


def prepare_modal(block, handler, directory, chunk_id):
    """Build native container commands without resolving any local SIF."""
    context = CommandContext()
    token = _COMMAND_CONTEXT.set(context)
    try:
        block._refresh_generated_command_template()
        manifest = block.create_manifest(handler, directory, chunk_id, write=True)
    finally:
        _COMMAND_CONTEXT.reset(token)
    if context.image is None:
        if block._get_image() is not None:
            raise ValueError(
                "Modal requires a command generated by the block's Image recipe; "
                "custom command_template overrides are not supported."
            )
        from chaperone.containers import Image

        context.image = Image("chaperone-cpu").base_image("ubuntu:24.04")
    return manifest, context


def validate_inputs(directory: Path, command: list[str], mounts: dict[str, str]):
    """Reject external symlinks and unstaged host paths before spending compute."""
    root = directory.resolve()
    for path in directory.rglob("*"):
        if path.is_symlink() and (
            path.is_dir() or not path.resolve().is_relative_to(root)
        ):
            raise ValueError(f"Modal input symlink is not a staged file: {path}")
    for arg in command:
        value = arg.partition("=")[2] if "=" in arg else arg
        for part in value.split(":"):
            path = Path(part)
            # '/' is also MPNN's sequence separator, not a host input.
            if path == Path("/") or not path.is_absolute() or not path.exists():
                continue
            if path.resolve().is_relative_to(root):
                continue
            if any(path.is_relative_to(mount) for mount in mounts):
                continue
            raise ValueError(
                f"Unstaged Modal input: {path}. Use stage_file() for inputs, or "
                "CHAPERONE_MODAL_VOLUMES for persistent checkpoints."
            )


def _extract_outputs(archive: Path, directory: Path):
    """Validate all returned paths before extracting into the local chunk."""
    with tarfile.open(archive) as source:
        for member in source.getmembers():
            # Inputs are packed with links dereferenced, and output artifacts
            # must be ordinary files/directories. Never accept remote links.
            if not (member.isfile() or member.isdir()):
                raise ValueError(
                    f"Unsupported Modal output archive entry: {member.name}"
                )
            tarfile.data_filter(member, str(directory))
        source.extractall(directory, filter="data")


def _checked_exec(sandbox, command, *, cwd=None, timeout=300):
    process = sandbox.exec(*command, workdir=cwd, timeout=timeout)
    # Drain both streams concurrently: large stderr must not block stdout.
    from concurrent.futures import ThreadPoolExecutor

    with ThreadPoolExecutor(max_workers=2) as pool:
        stdout = pool.submit(process.stdout.read)
        stderr = pool.submit(process.stderr.read)
        process.wait()
        out, err = stdout.result(), stderr.result()
    if out:
        print(out, end="")
    if err:
        print(err, end="")
    if process.returncode:
        raise subprocess.CalledProcessError(process.returncode, command, out, err)


def execute_modal(manifest, context: CommandContext, job_args):
    """Upload, execute, download; always terminate the Sandbox on exit."""
    try:
        import modal
    except ImportError as error:
        raise RuntimeError(
            "Install Modal support with: pip install 'chaperone[cloud]'"
        ) from error
    from chaperone import get_settings

    settings = get_settings()
    directory = Path(manifest.cwd).absolute()
    mounts = settings.CHAPERONE_MODAL_VOLUMES
    for mount in mounts:
        path = Path(mount)
        if not path.is_absolute() or path == Path("/"):
            raise ValueError(
                "Modal volume mount paths must be absolute and cannot be /"
            )
        if directory.is_relative_to(path) or path.is_relative_to(directory):
            raise ValueError(
                "Modal checkpoint volumes must not overlap the chunk directory"
            )
    for src, dest in context.explicit_binds:
        dest = dest.removesuffix(":ro")
        if not any(Path(dest).is_relative_to(mount) for mount in mounts):
            raise ValueError(
                f"Modal cannot use host bind {src} -> {dest}; stage the input "
                "or configure CHAPERONE_MODAL_VOLUMES."
            )
    validate_inputs(directory, manifest.command, mounts)
    timeout = settings.CHAPERONE_MODAL_TIMEOUT
    if job_args:
        timeout = min(timeout, max(1, job_args.timeout_min * 60))
    gpu = gpu_request(settings, job_args)
    with tempfile.TemporaryDirectory(prefix="chaperone-modal-") as temporary:
        temporary = Path(temporary)
        build_context = temporary / "image"
        build_context.mkdir()
        dockerfile = write_image_context(context.image, build_context)
        # Only this dedicated directory is a build context, including explicit
        # COPY sources. Never implicitly upload the client's repository.
        image = modal.Image.from_dockerfile(dockerfile, context_dir=build_context)
        archive = temporary / "inputs.tar"
        with tarfile.open(archive, "w", dereference=True) as packed:
            packed.add(directory, arcname=".")
        app = modal.App.lookup(settings.CHAPERONE_MODAL_APP, create_if_missing=True)
        volumes = {path: modal.Volume.from_name(name) for path, name in mounts.items()}
        sandbox = None
        try:
            with modal.enable_output():
                sandbox = modal.Sandbox.create(
                    "sleep",
                    "infinity",
                    image=image,
                    app=app,
                    gpu=gpu,
                    cpu=job_args.cpus_per_task if job_args else 1,
                    memory=job_args.mem_gb * 1024 if job_args else 1024,
                    timeout=timeout,
                    volumes=volumes,
                )
            logger.info("Modal sandbox %s, GPU=%s", sandbox.object_id, gpu or "none")
            gpu_count = (int(gpu.rsplit(":", 1)[1]) if ":" in gpu else 1) if gpu else 0
            context.allocation.start(sandbox.object_id, gpu_count)
            sandbox.filesystem.make_directory(str(directory))
            sandbox.filesystem.copy_from_local(archive, "/tmp/chaperone-inputs.tar")
            _checked_exec(
                sandbox,
                ["tar", "-xf", "/tmp/chaperone-inputs.tar", "-C", str(directory)],
            )
            # command_str already quotes ordinary arguments and preserves only
            # the operators explicitly supplied by a block (same as Manifest).
            _checked_exec(
                sandbox,
                ["/bin/sh", "-c", manifest.command_str],
                cwd=str(directory),
                timeout=timeout,
            )
            _checked_exec(
                sandbox,
                ["tar", "-cf", "/tmp/chaperone-outputs.tar", "-C", str(directory), "."],
            )
            output = temporary / "outputs.tar"
            sandbox.filesystem.copy_to_local("/tmp/chaperone-outputs.tar", output)
            _extract_outputs(output, directory)
        finally:
            if sandbox is not None:
                try:
                    sandbox.terminate()
                finally:
                    context.allocation.stop()
